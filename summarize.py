import argparse
from pathlib import Path
import pandas as pd
from common import load_config, load_json


def pair_table(cfg):
    df = pd.read_csv(cfg["paths"]["pairs"])
    rows = []
    for _, r in df.iterrows():
        base = Path(cfg["paths"]["prepared"]) / r.pair_id
        reg = base / "regions.json"
        rep = Path(cfg["paths"]["reports"]) / r.pair_id / "report.geojson"
        n = len(load_json(reg)["regions"]) if reg.exists() else ""
        c = load_json(rep)["counts"] if rep.exists() else {}
        rows.append({
            "pair": r.pair_id, "before": str(r.before_date)[:10], "after": str(r.after_date)[:10],
            "gap_days": round(r.gap_days), "verdict": r.verdict, "shift_px": round(float(r.shift_px), 2),
            "valid_fraction": round(float(r.valid_fraction), 2), "detected": n,
            "verified": c.get("verified", ""), "uncertain": c.get("uncertain", ""), "rejected": c.get("rejected", ""),
        })
    return pd.DataFrame(rows)


def top_changes(cfg):
    out = []
    for rep in sorted(Path(cfg["paths"]["reports"]).glob("*/report.geojson")):
        data = load_json(rep)
        for f in data["features"]:
            p = f["properties"]
            d = p["description"] or {}
            if p["status"] == "verified":
                out.append({"pair": data["pair"]["pair_id"], "region": p["region_id"], "area_m2": round(p["area_m2"]),
                            "type": d.get("change_type"), "description": d.get("description")})
    df = pd.DataFrame(out)
    return df.sort_values("area_m2", ascending=False).head(cfg["export"]["top_changes"]) if len(df) else df


def to_md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def run(cfg):
    pt, tc = pair_table(cfg), top_changes(cfg)
    parts = ["# Results", "", "Generated by `summarize.py` from the pipeline outputs.", "", "## Pairs", "", to_md(pt), ""]
    parts += ["## Largest verified changes", ""]
    parts += [to_md(tc) if len(tc) else "No verified changes yet. Run `python run.py interpret` first.", ""]
    Path(cfg["export"]["results_file"]).write_text("\n".join(parts), encoding="utf-8")
    return pt


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    cfg = load_config(ap.parse_args().config)
    print(run(cfg).to_string(index=False))


if __name__ == "__main__":
    main()
