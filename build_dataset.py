import argparse
import copy
import csv
from pathlib import Path
import pandas as pd
import rasterio
from common import ensure, get_logger, load_config, load_json
import discover
import pairing
import public_sets
from interpret import to_display
from pair_io import write_pair

log = get_logger("build_dataset")

ADAPTERS = {
    "levir_cd": [("Hugging Face mirror", public_sets.levir_hf), ("local folders", public_sets.paired_folders)],
    "whu_cd": [("local folders", public_sets.paired_folders)],
    "oscd": [("local OSCD folder", public_sets.oscd_local)],
    "xbd": [("local xBD folder", public_sets.xbd_local)],
    "spacenet7": [("public AWS bucket", public_sets.spacenet7_s3)],
}


def site_config(cfg, dcfg, site, k, windows):
    c = copy.deepcopy(cfg)
    base = Path(dcfg["sentinel2"]["work_dir"]) / site["name"] / f"try{k}"
    c["aoi"]["bbox"] = site["bbox"]
    c["pairing"]["windows"] = windows
    c["pairing"]["match_histograms"] = dcfg["sentinel2"]["match_histograms"]
    c["pairing"]["max_pairs_per_source"] = dcfg["sentinel2"]["pairs_per_site"]
    c["paths"] = {"work": str(base), "catalog": str(base / "catalog.csv"), "pairs": str(base / "pairs.csv"),
                  "prepared": str(base / "prepared"), "reports": str(base / "reports")}
    return c


def write_site_pairs(c, site, dcfg, oc):
    sc = dcfg["sentinel2"]
    written = 0
    for d in pairing.accepted_dirs(c)[: sc["pairs_per_site"]]:
        meta = load_json(d / "pair.json")
        with rasterio.open(d / "before.tif") as f:
            a = f.read()
        with rasterio.open(d / "after.tif") as f:
            b = f.read()
        ia, ib = to_display(a, meta["modality"], c["vlm"]), to_display(b, meta["modality"], c["vlm"])
        bd, ad = meta["before_date"][:10], meta["after_date"][:10]
        m = {"dataset": "Sentinel-2 L2A", "site": site["name"], "note": site["note"], "before_date": bd, "after_date": ad,
             "before_scene": meta["before_id"], "after_scene": meta["after_id"], "gsd_m": meta["res_m"],
             "crs": meta["crs"], "bbox_lonlat": site["bbox"], "source_url": sc["source_url"], "license": sc["license"],
             "processing": "windowed read of cloud-optimised GeoTIFFs, reprojected to UTM, per-band percentile stretch for display; no detections or outlines drawn"}
        write_pair(oc["root"], f"sentinel2/{site['name']}/{bd}_{ad}", ia, ib, m, oc)
        written += 1
    return written


def run_site(cfg, dcfg, site, oc):
    notes, written = [], 0
    for k, windows in enumerate(site["tries"]):
        label = f"try {k + 1} (before {windows['before']}, after {windows['after']})"
        c = site_config(cfg, dcfg, site, k, windows)
        try:
            cat = discover.run(c)
            if len(cat) == 0:
                notes.append(f"{label}: the scene search returned 0 scenes")
                continue
            pairing.run(c)
            written = write_site_pairs(c, site, dcfg, oc)
        except SystemExit as e:
            notes.append(f"{label}: {e}")
            continue
        except Exception as e:
            notes.append(f"{label}: {type(e).__name__}: {e}")
            continue
        if written:
            break
        df = pd.read_csv(c["paths"]["pairs"])
        notes.append(f"{label}: no pair passed verification; reasons: {df['reason'].value_counts().to_dict() if 'reason' in df else 'none recorded'}")
    return {"status": "ok" if written else "failed", "pairs": written, "notes": notes}


def run_public(key, c, oc):
    pct = oc["display_pct"]
    notes, written = [], 0
    for label, fn in ADAPTERS[key]:
        try:
            for item in fn(c, pct):
                meta = {"dataset": c["name"], "kind": c["kind"], "source_url": c["source_url"], "license": c["license"],
                        "date_note": c["date_note"], "before_date": c.get("before_date"), "after_date": c.get("after_date")}
                meta.update({k: v for k, v in item["meta"].items() if v is not None})
                write_pair(oc["root"], f"{key}/{item['rel']}", item["before"], item["after"], meta, oc)
                written += 1
        except Exception as e:
            notes.append(f"{label}: {type(e).__name__}: {e}")
        if written:
            break
    status = "ok" if written else "failed"
    if status == "failed":
        notes.append(f"How to obtain: {c['how_to_obtain']}")
    return {"status": status, "pairs": written, "notes": notes}


def write_report(results, dcfg):
    oc = dcfg["output"]
    lines = ["# Download report", "", "Generated by `build_dataset.py`. Every failure below is the exact message raised on the machine that ran the build.", "",
             "| Source | Status | Pairs saved |", "|---|---|---|"]
    lines += [f"| {k} | {v['status']} | {v['pairs']} |" for k, v in results.items()]
    for k, v in results.items():
        if v["notes"]:
            lines += ["", f"## {k}", ""] + [f"- {n}" for n in v["notes"]]
    Path(oc["report_file"]).write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_index(oc):
    rows = []
    for mj in sorted(Path(oc["root"]).rglob("meta.json")):
        m = load_json(mj)
        rows.append([mj.parent.relative_to(oc["root"]).as_posix(), m.get("dataset"), m.get("before_date"), m.get("after_date")])
    with open(oc["index_file"], "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["folder", "dataset", "before_date", "after_date"])
        w.writerows(rows)
    return len(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--dataset-config", required=True)
    ap.add_argument("--only", nargs="*")
    args = ap.parse_args()
    cfg, dcfg = load_config(args.config), load_config(args.dataset_config)
    oc = dcfg["output"]
    ensure(oc["root"])
    results = {}
    if dcfg["sentinel2"]["enabled"] and (not args.only or "sentinel2" in args.only):
        for site in dcfg["sentinel2"]["sites"]:
            results[f"sentinel2/{site['name']}"] = run_site(cfg, dcfg, site, oc)
    for key, c in dcfg["public"].items():
        if c["enabled"] and (not args.only or key in args.only):
            results[key] = run_public(key, c, oc)
    write_report(results, dcfg)
    log.info("pairs in index: %d", write_index(oc))
    for k, v in results.items():
        log.info("%s: %s, %d pairs", k, v["status"], v["pairs"])


if __name__ == "__main__":
    main()
